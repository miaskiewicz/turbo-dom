import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const require = createRequire(import.meta.url);
const path = process.argv[2], mode = process.argv[3], output = process.argv[4];
if (process.env.CSS_PROBE_NO_CRYPTO === '1') Object.defineProperty(globalThis, 'crypto', {value: undefined, configurable: true});
if (mode === 'native') Object.defineProperty(globalThis, 'WebAssembly', {value: undefined, configurable: true});
const started = performance.now();
const backend = require(path);
const loaded = performance.now();
assert.equal(backend.cssAbiVersion(), 1);
assert.equal(backend.cssBackendVersion(), '0.8.7');
const retained = object => typeof object.retainedBytes === 'function' ? object.retainedBytes() : object.retainedBytes;
const units = text => Array.from({length:text.length}, (_, index) => text.charCodeAt(index));
const computation = {maxNesting:32,maxOutputUnits:8192,maxTotalUnits:16384};
const css = '.x{text-decoration:underline dotted red;background:red;color:var(--c,blue);width:2em}@media(min-width:1000px){.x{color:red}}';
const model = new backend.CompiledStylesV1(JSON.stringify({abiVersion:1,sources:[{id:7,text:units(css)}],limits:{sources:4,sourceUnits:8192,rules:128,sourceRulePreludes:128,selectors:128,declarations:256,properties:1024,groupDepth:16,tokenNesting:32}}));
const metadata = JSON.parse(model.metadata());
const prepared = model.prepare(JSON.stringify({abiVersion:1,uses:[{sourceId:7,origin:'author',treeScope:0,scopeDepth:0,disabled:false,media:null}],environment:{mediaType:'screen',features:{width:{kind:'lengthPx',value:800}},unitBases:[['em',16],['rem',16]],selectorSupport:{},stylePhase:'steady'},limits:{uses:4,rules:128,layers:128,computation}}));
const selectorAnswers = metadata.selectors.flatMap(selector => selector.items.map(item => ({selectorId:selector.id,itemId:item.index,rootId:null,domainId:0,matches:[2]})));
const context = {initialColor:'rgb(0, 0, 0)',initialFontFamily:'serif',initialFontSize:'16px',unitBases:[['rem',16]],fontSizeUnitBases:[],isRoot:false};
const request = {abiVersion:1,domains:[{id:0,nodeIds:[2]}],selectorAnswers,scopeAnswers:[],targets:[{id:2,parentId:null,path:[2,1],implicitScopeRoot:1,treeScope:0,scopeDepth:0,pseudo:null,inline:null,context}],limits:{targets:8,answerRows:128,answerIds:1024,pathNodes:128,inputUnits:8192,retainedResultUnits:16384,matchingDecisions:1024,inlineDeclarations:128,inlineProperties:1024,customRollbacks:128,valueRetainedUnits:8192,computation}};
model.dispose();
const row = JSON.parse(prepared.resolveBatch(JSON.stringify(request))).targets[0];
const text = value => String.fromCharCode(...value);
assert.equal(text(row.values.color), 'rgb(0, 0, 255)');
assert.equal(text(row.values.width), '32px');
assert.equal(text(row.values['background-position-x']), '0%');
assert.equal(text(row.declaredTextDecoration.value), 'underline dotted red');
assert.equal(row.declaredTextDecoration.origin, 'author');
assert(row.publicKeys.includes('text-decoration-line'));
assert(!row.publicKeys.includes('font-weight'));
prepared.dispose();
assert.equal(retained(model), 0);
assert.equal(retained(prepared), 0);
assert.equal(text(row.declaredTextDecoration.value), 'underline dotted red');
const nativeModules = Object.keys(require.cache).filter(name => name.endsWith('.node'));
if (mode === 'wasm') assert.deepEqual(nativeModules, []);
writeFileSync(output, JSON.stringify({mode,node:process.version,module:path,sha256:createHash('sha256').update(readFileSync(path)).digest('hex'),loadMs:loaded-started,sourceSha256:createHash('sha256').update(css).digest('hex'),values:{color:text(row.values.color),width:text(row.values.width),backgroundPositionX:text(row.values['background-position-x']),declaredTextDecoration:text(row.declaredTextDecoration.value)},nativeModules,disposed:[retained(model),retained(prepared)],noCrypto:globalThis.crypto === undefined,noWebAssembly:mode==='native' && globalThis.WebAssembly===undefined},null,2)+'\n');
