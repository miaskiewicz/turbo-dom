#!/usr/bin/env bash
# Push the generated turbo-dom-v8 crate to the PR candidate branch so consumer PRs can
# `[patch.crates-io] turbo-dom-v8 = { git = ..., rev = ... }` before it is published.
#
#   scripts/push-candidate.sh [CRATE_DIR]      (default: crates/turbo-dom-v8/crate)
#
# The branch has its own (orphan) history with the crate at its root. Each run adds
# one commit on top when the crate changed; it never force-pushes. Prints the SHA.
# Env: TURBO_DOM_V8_REMOTE (default: this checkout's origin URL),
#      TURBO_DOM_V8_CANDIDATE_BRANCH (default: consolidation/turbo-dom-v8-candidate).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
crate="$(cd "${1:-$here/crate}" && pwd)"
branch="${TURBO_DOM_V8_CANDIDATE_BRANCH:-consolidation/turbo-dom-v8-candidate}"
remote="${TURBO_DOM_V8_REMOTE:-$(git -C "$here" remote get-url origin)}"
source_rev="$(git -C "$here" rev-parse HEAD)"

python3 "$here/scripts/generate.py" --verify "$crate" >&2
tree="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["generated"]["tree_sha256"])' "$here/pins.json")"

work="$(mktemp -d "${TMPDIR:-/tmp}/turbo-dom-v8-candidate.XXXXXX")"
trap 'rm -rf "${work:?}"' EXIT
git -C "$work" init -q
git -C "$work" remote add origin "$remote"
if git -C "$work" fetch -q --depth 1 origin "refs/heads/$branch" 2>/dev/null; then
  git -C "$work" checkout -q -b candidate FETCH_HEAD
  git -C "$work" rm -q -r --ignore-unmatch . >/dev/null
else
  git -C "$work" checkout -q --orphan candidate
fi
(cd "$crate" && find . -type f ! -path './target/*' ! -name Cargo.lock -print0 \
  | while IFS= read -r -d '' file; do
      mkdir -p "$work/$(dirname "$file")"
      cp "$file" "$work/$file"
    done)
git -C "$work" add -A
if git -C "$work" rev-parse -q --verify HEAD >/dev/null && git -C "$work" diff --cached --quiet; then
  echo "candidate unchanged" >&2
else
  git -C "$work" commit -q -F - <<EOF
turbo-dom-v8 150.4.0 candidate (generated tree ${tree:0:12})

Generated by crates/turbo-dom-v8/scripts/generate.py from miaskiewicz/turbo-dom
${source_rev}; generated tree sha256 ${tree}.
Throwaway PR candidate for [patch.crates-io] git rev pins; not a release.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
EOF
  git -C "$work" push -q origin "HEAD:refs/heads/$branch"
fi
git -C "$work" rev-parse HEAD
