SPEC = importlib.util.spec_from_file_location("turbo_dom_v8_generate", SCRIPTS / "generate.py")
GENERATE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(GENERATE)
PINS = GENERATE.load_pins()

