def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


class ManifestTransformTests(unittest.TestCase):
    def setUp(self):
        self.text = GENERATE.manifest(UPSTREAM_MANIFEST, PINS)
        self.result = tomllib.loads(self.text)

    def test_package_identity_license_links_and_metadata(self):
        package = self.result["package"]
        self.assertEqual(package["name"], "turbo-dom-v8")
        self.assertEqual(package["version"], "150.4.0")
        self.assertEqual(package["links"], "rusty_v8")
        self.assertEqual(package["rust-version"], "1.91")
        self.assertEqual(package["repository"], "https://github.com/miaskiewicz/turbo-dom")
        self.assertIn("fork of rusty_v8", package["description"])
        self.assertEqual(package["exclude"], ["*.md", "README*"])
        metadata = package["metadata"]["turbo-dom-v8"]
        self.assertEqual(metadata["upstream-package"], "v8")
        self.assertEqual(metadata["upstream-version"], "150.4.0")
        self.assertEqual(metadata["upstream-revision"], "5c15a6995c9bb4bacd3e341b59fff32c909c80bf")
        self.assertNotIn("Cargo.toml.orig", self.text)

    def test_library_keeps_the_v8_crate_name(self):
        self.assertEqual(self.result["lib"], {"name": "v8", "path": "src/lib.rs", "doctest": False})

    def test_icu_and_trybuild_targets_are_stripped_and_own_tests_added(self):
        names = [test["name"] for test in self.result["test"]]
        self.assertEqual(names, ["build", "slots", *GENERATE.OWN_TESTS])
        for test in self.result["test"][2:]:
            self.assertEqual(test["path"], f"tests/{test['name']}.rs")
        self.assertEqual(sorted(self.result["dev-dependencies"]), ["bytes"])

    def test_changed_upstream_layout_fails_instead_of_partial_rename(self):
        for old, new in [('name = "v8"\nversion', 'name = "other"\nversion'),
                         ('    "LICENSE*",\n', ""),
                         ("[[test]]\nname = \"test_ui\"", "[[test]]\nname = \"test_ui2\""),
                         ('path = "src/lib.rs"', 'path = "src/main.rs"'),
                         ("# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO", "# hand written")]:
            with self.assertRaises((GENERATE.GenerationError, KeyError)):
                GENERATE.manifest(UPSTREAM_MANIFEST.replace(old, new, 1), PINS)


class CommittedInputsTests(unittest.TestCase):
    def test_patch_hashes_are_pinned(self):
        self.assertEqual(sorted(PINS["patches"]), sorted(GENERATE.PATCHES))
        for name in GENERATE.PATCHES:
            self.assertEqual(sha256(GENERATE.CRATE / "patches" / name), PINS["patches"][name], name)

    def test_teardown_patch_is_turbo_surfs_reviewed_release_test_patch(self):
        self.assertEqual(PINS["patches"]["v8-teardown-tests.patch"],
                         "d5185408eb43c657f10dab2f0683c6797b2302d82a95823039164ac15df7e87c")

    def test_input_pins_are_turbo_surfs_reviewed_source(self):
        pinned = PINS["input"]
        self.assertTrue(pinned["patched_function_sha256"].startswith("b12f0237"))
        self.assertEqual(pinned["patched_isolate_sha256"],
                         "4eb4214ba55192c0146bd4eccef66b13b7fcbeaa0b79233fee3cf0ecc8836543")
        self.assertEqual(PINS["generated"]["key_files"]["src/function.rs"], pinned["patched_function_sha256"])
        self.assertEqual(PINS["generated"]["key_files"]["src/isolate.rs"], pinned["patched_isolate_sha256"])
        self.assertEqual(PINS["generated"]["key_files"]["LICENSE"], pinned["license_sha256"])

    def test_build_patch_pins_upstream_version_at_both_download_sites(self):
        patch = (GENERATE.CRATE / "patches/build-rs.patch").read_text()
        self.assertIn(f'+const UPSTREAM_V8_VERSION: &str = "{PINS["upstream"]["version"]}";', patch)
        self.assertEqual(patch.count('-  let version = env::var("CARGO_PKG_VERSION").unwrap();'), 1)
        self.assertEqual(patch.count('-    let version = env::var("CARGO_PKG_VERSION").unwrap();'), 1)
        self.assertEqual(patch.count("let version = UPSTREAM_V8_VERSION;"), 2)
        self.assertIn("fn upstream_v8_version_matches_pinned_upstream_release()", patch)
        added = [line for line in patch.splitlines() if line.startswith("+") and not line.startswith("+++")]
        self.assertFalse([line for line in added if "rust/vendor" in line or "update-rusty-v8" in line])
        self.assertTrue(any("crates/turbo-dom-v8/README.md" in line for line in added))

    def test_fork_marker_patch_exports_the_marker(self):
        patch = (GENERATE.CRATE / "patches/fork-marker.patch").read_text()
        self.assertIn("+pub const FORK_SHOULD_THROW_FIX: bool = true;", patch)

    def test_own_tests_exist_and_interceptor_tests_are_not_ignored(self):
        for name in GENERATE.OWN_TESTS:
            self.assertTrue((GENERATE.CRATE / "tests" / f"{name}.rs").is_file(), name)
        interceptor = (GENERATE.CRATE / "tests/interceptor_should_throw.rs").read_text()
        self.assertEqual(interceptor.count("#[test]"), 4)
        self.assertNotIn("#[ignore", interceptor)

    def test_rustfmt_uses_upstream_two_space_style(self):
        config = tomllib.loads((GENERATE.CRATE / "rustfmt.toml").read_text())
        self.assertEqual(config["tab_spaces"], 2)


class InputVerificationTests(unittest.TestCase):
    def test_modified_or_wrong_input_is_rejected_before_writing(self):
        with tempfile.TemporaryDirectory() as temporary:
            source = Path(temporary) / "input"
            (source / "src").mkdir(parents=True)
            (source / "src/function.rs").write_text("stock")
            (source / "src/isolate.rs").write_text("stock")
            (source / "LICENSE").write_text("MIT")
            (source / "Cargo.toml").write_text('[package]\nname = "v8"\nversion = "150.4.0"\n')
            output = Path(temporary) / "out"
            output.mkdir()
            with self.assertRaises(GENERATE.GenerationError):
                GENERATE.generate(source, output, PINS)
            self.assertEqual(list(output.iterdir()), [])

    def test_verify_rejects_a_tampered_generated_crate(self):
        with tempfile.TemporaryDirectory() as temporary:
            crate = Path(temporary)
            (crate / "Cargo.toml").write_text("[package]\n")
            with self.assertRaises(GENERATE.GenerationError):
                GENERATE.verify_output(crate, PINS)


@unittest.skipUnless(os.environ.get("TURBO_DOM_V8_INPUT"), "set TURBO_DOM_V8_INPUT to regenerate")
class RealInputTests(unittest.TestCase):
    def test_regeneration_matches_pins_and_verify(self):
        with tempfile.TemporaryDirectory() as temporary:
            out = Path(temporary)
            generated = GENERATE.generate(Path(os.environ["TURBO_DOM_V8_INPUT"]), out, PINS)
            self.assertEqual(GENERATE.verify_output(out, PINS), generated)
            build = generated["build.rs"].decode()
            self.assertNotIn('env::var("CARGO_PKG_VERSION")', build)
            self.assertFalse({"Cargo.toml.orig", "Cargo.lock", ".cargo_vcs_info.json"} & generated.keys())


if __name__ == "__main__":
    unittest.main()
