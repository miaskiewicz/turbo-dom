#!/usr/bin/env python3
"""Generate shared Rust indexes from the unchanged measured Blink registry."""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'crates/turbo-dom/src/rtdom/computed_css/property_registry.json'
OUTPUT = SOURCE.with_suffix('.rs')
def generated():
    raw = SOURCE.read_bytes()
    names = sorted(json.loads(raw)['properties'])
    rows = '\n'.join('    '+json.dumps(name)+',' for name in names)
    keyword_rows = '\n'.join('    ('+json.dumps(name)+', &['+', '.join(json.dumps(value) for value in row['keywords'])+']), ' for name,row in sorted(json.loads(raw)['properties'].items()) if row.get('keywords'))
    initial_rows = '\n'.join('    ('+json.dumps(name)+', '+json.dumps(row['initial'][0], ensure_ascii=False)+'),' for name,row in sorted(json.loads(raw)['properties'].items()) if len(row.get('initial', [])) == 1)
    return '''// Generated by scripts/generate-property-registry.py; do not edit.
//! Canonical measured property names and single-token initial profile values.
pub const REGISTRY_JSON: &str = include_str!("property_registry.json");
pub const SOURCE_SHA256: &str = "'''+hashlib.sha256(raw).hexdigest()+'''";
static NAMES: &[&str] = &[\n'''+rows+'''\n];
#[must_use]
pub fn is_known(name: &str) -> bool { NAMES.binary_search(&name).is_ok() }
#[must_use]
pub fn names() -> &'static [&'static str] { NAMES }
static KEYWORDS: &[(&str,&[&str])] = &[\n'''+keyword_rows+'''\n];
/// Positive keywords from measured metadata; this is not a complete value grammar.
#[must_use]
pub fn keywords(name:&str)->Option<&'static [&'static str]>{KEYWORDS.binary_search_by_key(&name,|row|row.0).ok().map(|index|KEYWORDS[index].1)}
static INITIAL_SINGLE_VALUES: &[(&str, &str)] = &[\n'''+initial_rows+'''\n];
/// One measured initial-profile value; this accessor does not select runtime policy.
/// Multi-value profiles and absent initial metadata remain None.
#[must_use]
pub fn initial_single_value(name: &str) -> Option<&'static str> {
    INITIAL_SINGLE_VALUES.binary_search_by_key(&name, |row| row.0).ok().map(|index| INITIAL_SINGLE_VALUES[index].1)
}
'''
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    text=subprocess.run(["rustup","run","1.98.0","rustfmt","--edition","2021","--emit","stdout"],input=generated(),text=True,capture_output=True,check=True).stdout
    if args.write: OUTPUT.write_text(text)
    elif OUTPUT.read_text()!=text: raise SystemExit('property registry generated source is stale')
if __name__=='__main__':main()
