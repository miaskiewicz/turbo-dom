#!/usr/bin/env python3
"""Generate turbo-dom-layout's `Vertical_Orientation` tables (UAX #50).

Reads local copies of two Unicode Character Database files (not downloaded at build
time; fetch them once, e.g. from https://www.unicode.org/Public/16.0.0/ucd/):
  VerticalOrientation.txt            the U / Tu ranges: the characters
                                     `text-orientation: mixed` sets upright (Blink sets
                                     U / Tu upright and turns R / Tr sideways; every code
                                     point not listed is R, the file's `@missing` default);
  auxiliary/GraphemeBreakProperty.txt  the Extend / ZWJ / SpacingMark ranges: combining
                                     marks, variation selectors, ZWJ, emoji modifiers and
                                     tags, which take the previous character's
                                     orientation instead of their own;
and writes `crates/turbo-dom-layout/src/layout/vertical_orientation.rs`.

Usage: python3 scripts/gen-vertical-orientation.py VerticalOrientation.txt GraphemeBreakProperty.txt [--out PATH]
       ... --check   (exit 1 when the committed table is stale)
"""
import argparse
import hashlib
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "crates/turbo-dom-layout/src/layout/vertical_orientation.rs"


def ranges_with(text, values):
    """The sorted, merged (first, last) ranges whose property value is in `values`."""
    ranges = []
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        cps, value = (part.strip() for part in data.split(";"))
        first, _, last = cps.partition("..")
        if value in values:
            ranges.append((int(first, 16), int(last or first, 16)))
    ranges.sort()
    merged = []
    for first, last in ranges:
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def source(name, text):
    version = re.search(name + r"-([\d.]+)\.txt", text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    return f"`{name}-{version.group(1) if version else '?'}.txt` (sha256 {digest})"


def table(name, ranges):
    rows = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in ranges)
    return f"pub(super) const {name}: &[(u32, u32)] = &[\n{rows}\n];\n"


def render(orientation, grapheme):
    missing = re.findall(r"#\s*@missing:\s*(\S+)\s*;\s*(\w+)", orientation)
    if missing != [("0000..10FFFF", "R")]:
        raise SystemExit(f"unexpected @missing defaults: {missing}")
    return (
        "//! GENERATED by `scripts/gen-vertical-orientation.py` from the Unicode Character\n"
        f"//! Database's {source('VerticalOrientation', orientation)}\n"
        f"//! and {source('GraphemeBreakProperty', grapheme)}; do not edit.\n"
        "#![allow(clippy::unreadable_literal)] // code points as the UCD writes them\n"
        "\n"
        "/// The code point ranges whose `Vertical_Orientation` (UAX #50) is U or Tu: the\n"
        "/// characters `text-orientation: mixed` sets upright (everything else is R / Tr).\n"
        "/// Sorted, disjoint, merged `(first, last)` ranges (inclusive).\n"
        + table("UPRIGHT", ranges_with(orientation, {"U", "Tu"}))
        + "\n"
        "/// The code point ranges whose `Grapheme_Cluster_Break` is `Extend`, `ZWJ` or\n"
        "/// `SpacingMark`: marks, variation selectors, ZWJ, emoji modifiers and tags, which\n"
        "/// take the previous character's orientation. Sorted, disjoint, merged.\n"
        + table("INHERIT", ranges_with(grapheme, {"Extend", "ZWJ", "SpacingMark"}))
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("orientation")
    parser.add_argument("grapheme")
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    read = lambda path: pathlib.Path(path).read_text(encoding="utf-8")  # noqa: E731
    generated = render(read(args.orientation), read(args.grapheme))
    out = pathlib.Path(args.out)
    if args.check:
        if out.read_text(encoding="utf-8") != generated:
            print(f"{out} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    out.write_text(generated, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
