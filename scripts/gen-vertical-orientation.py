#!/usr/bin/env python3
"""Generate turbo-dom-layout's `Vertical_Orientation` table (UAX #50).

Reads a local copy of the Unicode Character Database's `VerticalOrientation.txt` (not
downloaded at build time; fetch it once, e.g. from
https://www.unicode.org/Public/16.0.0/ucd/VerticalOrientation.txt) and writes
`crates/turbo-dom-layout/src/layout/vertical_orientation.rs`: the merged code point
ranges whose value is U or Tu, the characters `text-orientation: mixed` sets upright
(Blink sets U / Tu upright and turns R / Tr sideways). Every code point not listed is R
(the file's `@missing` default).

Usage: python3 scripts/gen-vertical-orientation.py PATH/VerticalOrientation.txt [--out PATH]
       python3 scripts/gen-vertical-orientation.py PATH --check   (exit 1 when stale)
"""
import argparse
import hashlib
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "crates/turbo-dom-layout/src/layout/vertical_orientation.rs"
UPRIGHT = {"U", "Tu"}


def upright_ranges(text):
    """The sorted, merged (first, last) ranges whose value is U or Tu."""
    missing = [m for m in re.findall(r"#\s*@missing:\s*(\S+)\s*;\s*(\w+)", text)]
    if missing != [("0000..10FFFF", "R")]:
        raise SystemExit(f"unexpected @missing defaults: {missing}")
    ranges = []
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        cps, value = (part.strip() for part in data.split(";"))
        first, _, last = cps.partition("..")
        if value in UPRIGHT:
            ranges.append((int(first, 16), int(last or first, 16)))
    ranges.sort()
    merged = []
    for first, last in ranges:
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def render(text):
    version = re.search(r"VerticalOrientation-([\d.]+)\.txt", text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    rows = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in upright_ranges(text))
    return (
        "//! GENERATED by `scripts/gen-vertical-orientation.py` from the Unicode Character\n"
        f"//! Database's `VerticalOrientation-{version.group(1) if version else '?'}.txt`\n"
        f"//! (sha256 {digest}); do not edit.\n"
        "//!\n"
        "//! The code point ranges whose `Vertical_Orientation` (UAX #50) is U or Tu: the\n"
        "//! characters `text-orientation: mixed` sets upright. Everything else is R / Tr.\n"
        "\n"
        "/// Sorted, disjoint, merged `(first, last)` ranges (inclusive).\n"
        "pub(super) const UPRIGHT: &[(u32, u32)] = &[\n"
        f"{rows}\n"
        "];\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(pathlib.Path(args.source).read_text(encoding="utf-8"))
    out = pathlib.Path(args.out)
    if args.check:
        if out.read_text(encoding="utf-8") != generated:
            print(f"{out} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    out.write_text(generated, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
