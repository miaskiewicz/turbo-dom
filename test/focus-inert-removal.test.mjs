import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createEnvironment } from '../src/runtime/index.mjs';
import { cssFocusTarget } from '../src/runtime/css-invalidation.mjs';

test('inert reflects the own boolean attribute and blocks focus through a slot', () => {
  const { document: d, window } = createEnvironment('<button id="old"></button><main inert="false"><button id="next"></button></main>');
  const old = d.querySelector('#old'), main = d.querySelector('main'), next = d.querySelector('#next');
  const descriptor = Object.getOwnPropertyDescriptor(window.HTMLElement.prototype, 'inert');
  assert.equal(typeof descriptor?.set, 'function');
  old.focus();
  assert.equal(main.inert, true);
  assert.equal(next.inert, false);
  let focused = 0;
  next.addEventListener('focus', () => focused++);
  next.focus();
  assert.equal(d.activeElement, old);
  assert.equal(focused, 0);
  main.inert = false;
  assert.equal(main.hasAttribute('inert'), false);
  const root = main.attachShadow({ mode: 'closed' });
  const slot = d.createElement('slot');
  root.appendChild(slot);
  slot.inert = 'false';
  assert.equal(slot.getAttribute('inert'), '');
  next.focus();
  assert.equal(d.activeElement, old);
  slot.removeAttribute('inert');
  next.focus();
  assert.equal(d.activeElement, next);
  assert.equal(focused, 1);
  main.inert = true;
  const inner = d.createElement('button'); root.appendChild(inner);
  inner.focus();
  assert.notEqual(d.activeElement, inner);
});

test('removing a focused node or ancestor clears focus even when it is immediately reinserted', () => {
  const { document: d } = createEnvironment('<main><button></button></main><aside></aside>');
  const main = d.querySelector('main'), b = d.querySelector('button');
  b.focus();
  d.querySelector('aside').remove();
  assert.equal(d.activeElement, b);
  b.remove(); main.appendChild(b);
  assert.equal(d.activeElement, d.body);
  assert.equal(cssFocusTarget(d), null);
  b.focus(); main.remove(); d.body.append(main);
  assert.equal(d.activeElement, d.body);
  b.focus(); main.replaceChildren();
  assert.equal(d.activeElement, d.body);
  b.focus();
  assert.equal(d.activeElement, d.body);
  main.appendChild(b); b.focus(); b.textContent = 'still focused';
  assert.equal(d.activeElement, b);
  const host = d.createElement('div'); main.append(host);
  const inner = d.createElement('input'); host.attachShadow({mode:'open'}).append(inner);
  inner.focus(); main.innerHTML = '';
  assert.equal(d.activeElement, d.body);
  d.body.focus(); d.body.remove();
  assert.equal(d.activeElement, null);
});
